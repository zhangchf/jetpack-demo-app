import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

@LargeTest
@HiltAndroidTest
class DemoNavigationActivityTest2 {

    @get:Rule(order = 0)
    var hiltRule = HiltAndroidRule(this)

    @Rule(order = 1)
    @JvmField
    var mActivityTestRule = ActivityTestRule(DemoNavigationActivity::class.java)

    @Before
    fun init() {
        hiltRule.inject()
    }

    @Test
    fun demoNavigationActivityTest2() {
        val bottomNavigationItemView = onView(
            allOf(
                withId(R.id.bottomNav3Fragment), withContentDescription("Page 3"),
                childAtPosition(
                    childAtPosition(
                        withId(R.id.bottomNavigationView),
                        0
                    ),
                    2
                ),
                isDisplayed()
            )
        )
        bottomNavigationItemView.perform(click())

        val textView = onView(
            allOf(
                withId(R.id.text_view),
                withText("Post 2 body"),
                withParent(withParent(withId(R.id.recycler_view))),
                isDisplayed()
            )
        )
        textView.check(matches(withText("Post 2 body")))
    }

    private fun childAtPosition(
        parentMatcher: Matcher<View>, position: Int
    ): Matcher<View> {

        return object : TypeSafeMatcher<View>() {
            override fun describeTo(description: Description) {
                description.appendText("Child at position $position in parent ")
                parentMatcher.describeTo(description)
            }

            public override fun matchesSafely(view: View): Boolean {
                val parent = view.parent
                return parent is ViewGroup && parentMatcher.matches(parent)
                        && view == parent.getChildAt(position)
            }
        }
    }
}
